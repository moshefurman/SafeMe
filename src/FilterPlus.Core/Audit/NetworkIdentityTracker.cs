namespace FilterPlus.Core.Audit;

/// <summary>
/// עוקב אחרי זהות הרשת, ואומר מתי היא התחלפה.
///
/// הביקורת רצה על שעון של חמש עשרה דקות. זה הגיוני כשהמחשב יושב
/// באותו מקום, ושגוי לגמרי ברגע שהוא עובר רשת: הספק, הציון ורמת
/// ההגנה נשארים על התשובה של הרשת הקודמת עד הביקורת הבאה.
///
/// כך זה נראה בשטח — מחשב שהתנתק מרימון והמשיך להציג "מוגן · רימון ·
/// בסיסית" כרבע שעה. זו לא תקלת זיהוי; זו תשובה נכונה על שאלה שכבר
/// לא רלוונטית. עבור תוכנה שכל תפקידה לומר אם המחשב מסונן עכשיו,
/// זה הפרש שמבטל את התשובה.
///
/// המעקב מופרד מהאכיפה בכוונה. שם כבר יש זיהוי החלפת רשת, אבל הוא
/// יוצא מוקדם כשאין הכרעה קודמת — נכון לצורך שלו, ולא מספיק לצורך
/// הזה. שני צרכנים לאותה עובדה, כל אחד עם התנאים שלו.
/// </summary>
public sealed class NetworkIdentityTracker
{
    private string? _last;

    /// <summary>
    /// האם הרשת התחלפה מאז הקריאה הקודמת.
    ///
    /// זהות לא ידועה אינה נחשבת החלפה. מתאם שירד לרגע, VPN שעולה,
    /// או רגע בין ניתוק לחיבור — כולם מחזירים ריק, וביקורת שתרוץ
    /// בדיוק אז תמדוד רשת שאינה קיימת. עדיף להמתין לזהות אמיתית.
    ///
    /// גם התצפית הראשונה אינה החלפה. היא קובעת את קו הבסיס, והביקורת
    /// ממילא רצה עשר שניות אחרי עליית השירות.
    /// </summary>
    public bool Changed(string? identity)
    {
        if (string.IsNullOrWhiteSpace(identity)) return false;

        var previous = _last;
        _last = identity;

        if (previous is null) return false;

        return !string.Equals(previous, identity, StringComparison.OrdinalIgnoreCase);
    }
}
