ALTER TABLE network_sessions
  ADD CONSTRAINT network_sessions_outcome_check
  CHECK (outcome IN ('allowed', 'blocked', 'pending', 'observed'));

COMMENT ON COLUMN network_sessions.outcome IS
  'מה קרה בפועל. observed = ההכרעה הייתה לחסום, והאכיפה במצב תצפית לא חסמה.';
