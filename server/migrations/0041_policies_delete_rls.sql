-- ============================================================================
--  SafeMe · 0041 · מחיקת שורת מדיניות, שמעולם לא עבדה
--
--  0006 הגדירה לטבלת policies שלוש מדיניות RLS — קריאה, הוספה ועדכון —
--  ולא רביעית למחיקה. כש-RLS פעיל ואין מדיניות לפעולה, הפעולה אינה
--  נכשלת: היא פשוט אינה רואה שורות. DELETE מחזיר "0 שורות נמחקו",
--  בלי שגיאה, לכל מי שאינו בעל הטבלה.
--
--  ההרכבה מחדש (policy/recompose.ts) מוחקת את שורת המדיניות של מחשב
--  שחזר לבסיס, וההערה שם מסבירה למה זה הכרחי: שורה שנשארת בלי שיוך
--  נושאת tenant_id ומספר גרסה גבוה, ולכן נראית בדיוק כמו מדיניות
--  הדייר — ונבחרת כזו. המחיקה הזו רצה בכל עליית שרת ולא מחקה דבר
--  אף פעם.
--
--  נמדד, לא הוסק: סקריפט הבדיקה של הרשימה הלבנה ספר את השורות אחרי
--  עשרה פרסומים ומצא את כל העשר.
--
--  עם רשימה לבנה המחיר עולה. שארית של שעות חסימה שנבחרת כמדיניות
--  הדייר חוסמת את שאר המחשבים בשעות של אח שלהם; שארית של רשימה
--  לבנה הייתה נועלת את כולם לרשימה של מחשב אחד.
--
--  דייר רשאי למחוק רק את שלו. התבנית הגלובלית (tenant_id IS NULL)
--  נשארת בידי הפלטפורמה בלבד, כמו בכתיבה.
--
--  ההרשאה עצמה (GRANT DELETE) כבר ניתנה ב-0006.
-- ============================================================================

CREATE POLICY policies_delete ON policies FOR DELETE
  USING (app.is_platform() OR tenant_id = app.current_tenant());
