/*
 * ספק האינטרנט, כחלק מזהות הרשת.
 *
 * רשת אלחוטית לבדה אינה זהות מספקת. אותו נתב, אותו שם, אותה כתובת
 * חומרה — וקו אחר מאחוריו. מי שהחליף את הקו המסונן בקו פתוח לא שינה
 * דבר שהמערכת ידעה להסתכל עליו, והאישור הישן המשיך לכסות אותו.
 *
 * הספק אינו נכנס ל-fingerprint. טביעת האצבע היא זהות הנתב הפיזי,
 * וההיסטוריה נשמרת סביבה; קריאת הספק יוצאת לרשת ונכשלת לפעמים,
 * ומזהה שמשתנה עם כל כישלון קריאה היה מפצל את ההיסטוריה ומייצר
 * רשתות רפאים. הוא נשמר לצד הרשת, והאישור נבדק מולו.
 */

-- ---------------------------------------------------------------- הרשת

ALTER TABLE known_networks
  /*
   * מזהה ה-ASN, לא השם.
   *
   * השם הוא טקסט חופשי שמשתנה עם מיתוג ועם מי שהקליד אותו במאגר.
   * המספר מוקצה ליישות שמנתבת את התעבורה, והוא מה שמושווה.
   */
  ADD COLUMN isp_key text,

  /* השם, לתצוגה בלבד. אין השוואה מולו. */
  ADD COLUMN isp_name text,

  /*
   * הספק שעבורו ניתן האישור.
   *
   * נפרד מ-isp_key: זה מה שנצפה עכשיו, וזה מה שההורה אישר. כשהם
   * נפרדים, הרשת חוזרת להמתנה.
   *
   * NULL ברשת שאושרה לפני שהשדה היה קיים. במקרה כזה אין מול מה
   * להשוות, והאישור נשאר בתוקף — הרחבה של הגנה אינה אמורה לנעול
   * רטרואקטיבית משפחות שכבר אישרו את הרשת בבית.
   */
  ADD COLUMN approved_isp text;

COMMENT ON COLUMN known_networks.isp_key IS
  'ספק האינטרנט שנצפה לאחרונה מאחורי הרשת. AS<מספר>, או שם כשאין מספר.';

COMMENT ON COLUMN known_networks.approved_isp IS
  'הספק שעבורו ניתן האישור. שונה מ-isp_key מחזיר את הרשת להמתנה.';

-- ---------------------------------------------------------------- הסשן

/*
 * וגם בהיסטוריה.
 *
 * כאן זה נשמר לכל חיבור בנפרד, ולא רק "האחרון שנראה": השאלה
 * שההורה ישאל היא "מתי זה השתנה", ולשם כך צריך את השרשרת ולא
 * את נקודת הסיום.
 */
ALTER TABLE network_sessions
  ADD COLUMN isp_key  text,
  ADD COLUMN isp_name text;

COMMENT ON COLUMN network_sessions.isp_key IS
  'ספק האינטרנט בזמן החיבור הזה. מאפשר לראות החלפת קו בלי החלפת רשת.';

/*
 * שאילתת "מתי הספק התחלף ברשת הזו" רצה על מכשיר ורשת, לפי זמן.
 * האינדקס הקיים הוא על מכשיר בלבד.
 */
CREATE INDEX network_sessions_isp_idx
  ON network_sessions (network_id, started_at DESC)
  WHERE isp_key IS NOT NULL;
