-- ============================================================================
--  SafeMe · 0014 · דגימת פעימות
--
--  עד כה נשמרה שורה בטבלת heartbeats לכל פעימה. מכשיר אחד שולח
--  480 פעימות ביום, ובהיקף של 4,000 מכשירים זה 58 מיליון שורות
--  בחודש — כ-30 ג'יגה עם אינדקסים, עבור נתונים שאיש אינו קורא.
--
--  ההבחנה שמאפשרת לצמצם: device_state מחזיקה את המצב **החי**, שורה
--  אחת למכשיר, והיא מה שהדשבורד קורא. טבלת heartbeats היא היסטוריה
--  בלבד — לחקירה ולתחקיר. היסטוריה לא חייבת לכלול 480 שורות זהות
--  ביום שבו לא קרה דבר.
--
--  מכאן: המצב החי מתעדכן בכל פעימה כמקודם, ושורת היסטוריה נשמרת רק
--  כשמשהו השתנה, ובנוסף אחת לשעה כסימן חיים.
--
--  סימן החיים השעתי אינו קישוט: בלעדיו אי אפשר להבדיל בין "המכשיר
--  היה תקין ושקט" לבין "המכשיר לא דיבר איתנו", ושתי המסקנות האלה
--  הפוכות זו לזו בדיוק בתחקיר שבשבילו נשמרת הטבלה.
-- ============================================================================

ALTER TABLE device_state
  ADD COLUMN last_sample_at timestamptz;

COMMENT ON COLUMN device_state.last_sample_at IS
  'מתי נשמרה לאחרונה שורת היסטוריה בפועל. מניע את סימן החיים השעתי.';

COMMENT ON TABLE heartbeats IS
  'היסטוריית פעימות, דגומה. שורה נשמרת בשינוי מצב או אחת לשעה — '
  'ולא בכל פעימה. המצב החי נמצא ב-device_state.';

-- מכשירים קיימים: אין להם דגימה קודמת, ולכן הפעימה הבאה שלהם תישמר.
-- זו ההתנהגות הרצויה — מתחילים כל אחד מנקודת ייחוס מוכרת.
UPDATE device_state SET last_sample_at = NULL;
