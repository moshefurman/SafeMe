-- ============================================================================
--  SafeMe · 0038 · מסירת התראות
--
--  מסך ההתראות הציע להורה חמישה סוגי התראה, שלושה ערוצים לכל אחד,
--  ושעות שקט. השרת שלח סוג אחד בלבד — מחשב ששתק — תמיד מיד, ובלי
--  להביט בשעון. ארבעת האחרים נשמרו במסד ולא קראו אותם מעולם.
--
--  והסוג האחד שכן נשלח, נשלח פעם אחת: ההתראה שנפתחה לא נסגרה כשהמחשב
--  חזר, ולכן השתיקה הבאה לא פתחה התראה חדשה ולא שלחה דבר.
--
--  שתי העמודות כאן הן מה שחסר כדי שהמסך יאמר את האמת:
--
--    detail    מה קרה, בנוסח להורה. נדרש כדי שסיכום יומי יוכל
--              לומר מה היה, ולא רק שהיה משהו.
--    deferred  ההתראה ממתינה למשלוח מאוחר — סיכום יומי, שעות שקט,
--              או שליחה שנכשלה ותנוסה שוב. בלי הסימון, "יומי" ו"שקט"
--              היו שם נרדף ל"לעולם לא".
-- ============================================================================

ALTER TABLE alerts
  ADD COLUMN detail   text,
  ADD COLUMN deferred boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN alerts.detail IS
  'מה קרה, בנוסח שמוצג להורה. מועתק להודעה ולסיכום.';

COMMENT ON COLUMN alerts.deferred IS
  'ממתינה למשלוח מאוחר: סיכום יומי, שעות שקט, או ניסיון חוזר.';

/*
 * אינדקס חלקי לעובד הסיכום, שסורק רק את הממתינות.
 *
 * הטבלה גדלה עם כל אירוע, והממתינות הן קומץ. סריקה מלאה כל חמש
 * דקות הייתה עלות שגדלה עם ההיסטוריה במקום עם העבודה.
 */
CREATE INDEX alerts_deferred_idx ON alerts (tenant_id) WHERE deferred;

-- ---------------------------------------------------------------- הסיכום היומי

/*
 * מתי יצא הסיכום האחרון.
 *
 * "יומי" צריך עוגן: בלעדיו כל סריקה הייתה שולחת סיכום חדש, וההורה
 * שביקש פחות היה מקבל יותר.
 */
ALTER TABLE notification_settings
  ADD COLUMN last_digest_at timestamptz;

COMMENT ON COLUMN notification_settings.last_digest_at IS
  'מתי נשלח הסיכום היומי האחרון. ריק = מעולם לא.';
