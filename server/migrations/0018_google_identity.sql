--
--  משתמש שנרשם דרך Google אין לו סיסמה ולא אמורה להיות לו — סיסמה
--  שנוצרת אוטומטית היא סוד שאיש אינו יודע ואיש אינו מסובב, וכל
--  ערכה הוא בכך שהעמודה אינה ריקה.
