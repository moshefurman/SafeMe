ALTER TABLE users
  ADD COLUMN google_sub text UNIQUE,
  /* מתי הזהות קושרה. מוצג למשתמש במסך החשבון. */
  ADD COLUMN google_linked_at timestamptz,
  ALTER COLUMN password_hash DROP NOT NULL;

/*
 * חשבון חייב דרך כניסה אחת לפחות.
 *
 * הסרת NOT NULL לבדה הייתה מאפשרת משתמש בלי סיסמה ובלי זהות
 * חיצונית — חשבון שאי אפשר להיכנס אליו, ושנוצר בשקט בכל באג
 * שמדלג על אחד השדות.
 */
ALTER TABLE users
  ADD CONSTRAINT users_has_a_way_in CHECK (
    password_hash IS NOT NULL OR google_sub IS NOT NULL
  );

/*
 * זהות שקושרה מחייבת מועד, ומועד מחייב זהות.
 *
 * אותה תבנית כמו network_decision_has_time: שני שדות שמתארים
 * אירוע אחד אינם יכולים להיות חצי מלאים.
 */
ALTER TABLE users
  ADD CONSTRAINT users_google_link_has_time CHECK (
    (google_sub IS NULL) = (google_linked_at IS NULL)
  );

COMMENT ON COLUMN users.google_sub IS
  'מזהה המשתמש אצל Google. יציב, ואינו משתנה כשהמייל משתנה.';

