/*
 * קוד הסרה שאפשר להכתיב בטלפון.
 *
 * הקוד נחתם ב-RSA, והחתימה היא כשש מאות תווים בבסיס 64. זה עובד
 * כשמדביקים, ואי אפשר להכתיב את זה בטלפון — כלומר מסלול המוקד לא
 * היה שמיש בדיוק במצב שבשבילו הוא קיים: מחשב חסום, בלי אינטרנט,
 * והורה שמחייג.
 *
 * הסוכן יודע לאמת קוד קצר מהיום הראשון: HMAC קטוע לחמישה עשר
 * בתים, Base32 Crockford, עשרים וארבעה תווים בארבע קבוצות.
 * המנגנון היה בנוי ומעולם לא נבחר, כי בצד השרת לא היה מי שיפיק
 * אותו.
 *
 * הסוד עצמו אינו נשמר כאן. הוא נגזר בכל פעם ממפתח ראשי:
 *
 *     deviceSecret = HMAC(master, 'safeme:uninstall:v1|' || hwid)
 *
 * ובייצור המפתח הראשי יושב ב-KMS ואינו יוצא ממנו. עמודת סוד לכל
 * מחשב הייתה הופכת דליפת מסד לפתיחת כל הצי בבת אחת — וזה בדיוק
 * מה שהמפתח ב-KMS נועד למנוע במסלול ה-RSA.
 */

ALTER TABLE devices
  /*
   * באיזה מצב המחשב הזה מאמת קוד הסרה.
   *
   * נקבע ברישום ואינו משתנה: הסוכן שומר את המצב ואת הסוד שלו
   * מקומית, ושינוי מהשרת היה משאיר אותו מאמת בשיטה אחרת מזו
   * שבה הקוד הונפק.
   *
   * ברירת המחדל היא rsa, ובכוונה. מחשבים שכבר רשומים לא קיבלו
   * סוד מעולם, והם ימשיכו לאמת ב-RSA עד שיירשמו מחדש. שינוי
   * ברירת המחדל היה שובר אותם בשקט.
   */
  ADD COLUMN uninstall_key_mode text NOT NULL DEFAULT 'rsa'
    CHECK (uninstall_key_mode IN ('rsa', 'hmac'));

COMMENT ON COLUMN devices.uninstall_key_mode IS
  'rsa: חתימה ארוכה, להדבקה. hmac: 24 תווים, להכתבה בטלפון. נקבע ברישום.';

/*
 * ---------------------------------------------------------------- אבחון
 *
 * כמה מחשבים עדיין במצב הארוך.
 *
 * לא מדד סקרנות: כל מחשב כזה הוא שיחת טלפון שאי אפשר לסיים בה
 * את ההסרה. המספר צריך לרדת לאפס, וכל עוד הוא לא — יש לקוחות
 * שהמוקד לא יוכל לשרת.
 */
CREATE INDEX devices_uninstall_key_mode_idx
  ON devices (uninstall_key_mode) WHERE uninstall_key_mode = 'rsa';
