/*
 * כתובת לפניות, שמוצגת למשתמשים.
 *
 * הפורטל אומר להורה "ההסרה תיעשה דרך המוקד בלבד, יש לפנות אליו"
 * ואינו אומר איך. זה מבוי סתום בדיוק ברגע שבו הוא הכי צריך עזרה,
 * והוא ייגמר בחיפוש בגוגל או בוויתור.
 *
 * אותו חוסר מופיע בהודעת החשבון המושעה, ובמסך הכניסה.
 *
 * ---
 *
 * במסך הדואר ולא בטבלה נפרדת.
 *
 * זו הגדרה של הפלטפורמה כמו כתובת השולח, היא משתנה יחד איתה,
 * והיא שורה אחת. טבלה משלה הייתה מקום נוסף לשכוח לעדכן.
 *
 * שונה מ-reply_to: זו כתובת שמוצגת בממשק, ואילו reply_to הוא
 * לאן חוזרת תשובה על הודעה שנשלחה. לרוב זו אותה כתובת, ולא תמיד —
 * ואיחודן היה כובל שתי החלטות שאין ביניהן קשר.
 */

ALTER TABLE mail_settings ADD COLUMN support_email text;

COMMENT ON COLUMN mail_settings.support_email IS
  'כתובת לפניות, מוצגת בפורטל. ריק = לא מוצג דבר.';
