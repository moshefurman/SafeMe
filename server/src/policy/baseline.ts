/**
 * מדיניות ברירת מחדל גלובלית.
 *
 * נוצרה אחרי שנפל בשטח: מחשב שנרשם לחשבון חדש קיבל 404 על משיכת
 * המדיניות, ורץ בלי הגדרות בכלל. הסוכן אמנם מתנהג שמרנית בלי
 * מדיניות, אבל "בלי מדיניות" אינו מצב שאמור להתקיים — הוא רק אומר
 * שאיש לא הגדיר מה נכון.
 *
 * הרשומה הגלובלית חלה על כל דייר שאין לו מדיניות משלו: השאילתה
 * ב-/api/v1/policy כבר נופלת אליה אחורה. מה שהיה חסר הוא שהיא
 * תתקיים.
 *
 * מצב תצפית, בשלב הפיילוט.
 *
 * monitor ו-warn: המחשב מודד הכול ומדווח הכול, ואינו חוסם על סמך
 * מסקנה שהוא הסיק בעצמו. מה שכן נאכף — רשת שנחסמה במפורש, נעילה
 * יזומה, וחלונות זמן — הן החלטות של ההורה ולא של הסוכן.
 *
 * הסיבה אינה זהירות כללית: המוצר נעל מחשב אמיתי פעמיים, בשני
 * מנגנונים שונים, ובשניהם החסימה מנעה את הבדיקה שהייתה משחררת
 * אותה. שני הגורמים תוקנו, אבל תיקון שלא נצפה בשטח אינו תיקון
 * מוכח.
 *
 * להפעלת האכיפה: enforce ו-lockout כאן **וגם** ברצפת אסימון
 * ההרשמה. שני המקומות, תמיד יחד.
 *
 * המדיניות תואמת לרצפת ברירת המחדל, ולא מקלה ממנה.
 *
 * הניסיון הראשון היה monitor, מתוך מחשבה שמחשב שהרגע הותקן אינו
 * המקום להתחיל בחסימה. בשטח הסוכן דחה אותה: המחשב נרשם עם רצפת
 * enforce, והרצפה אינה מרשה לרדת מתחתיה — בצדק, זה כל תפקידה.
 *
 * התוצאה הייתה הגרועה משתי האפשרויות: לא רק שהמדיניות לא הקלה,
 * היא לא חלה בכלל, וכללי זיהוי הספקים לא הגיעו לאף מחשב. תבנית
 * שנמוכה מכל רצפה היא תבנית שאינה קיימת.
 *
 * מה שמונע את הנעילה שממנה חששתי אינו מצב האכיפה אלא שלוש רשתות
 * הביטחון שנבנו מאז: הרשת שממנה מתקינים מאושרת מאליה, מארח הפורטל
 * נשאר פתוח גם בחסימה, וזיהוי הספקים סוף סוף עובד.
 *
 * ו-default-deny כבוי. הפעלתו היא החלטה מפורשת בפורטל, ולא משהו
 * שקורה למישהו כי השרת עלה.
 */

/*
 * גרסת התבנית.
 *
 * מועלית בכל שינוי בתוכן, וזה מה שגורם לו לחול. בלי המספר הזה
 * "אינה דורסת קיימת" הייתה אומרת שכל תיקון בתבנית אינו מגיע לשום
 * מקום שכבר רץ — וזה בדיוק מה שקרה עם מארח הפורטל.
 *
 * 1 — התבנית הראשונה
 * 2 — מארח הפורטל ב-alwaysAllow, כדי שחסימה לא תנעל גם את המסך
 *     שמסיר אותה
 * 3 — כללי זיהוי לספקים. עד כה הם נמנו בשם בלבד, ולכן שום ספק
 *     לא זוהה אף פעם
 * 4 — תואם לרצפה. גרסה 3 נדחתה בכל מחשב כי הייתה מקלה ממנה,
 *     ולכן גם כללי הזיהוי שבה לא הגיעו לשום מקום
 * 5 — זיהוי לפי מנפיק התעודה. הווקטור היחיד שעובד לספק שמסנן
 *     דרך פרוקסי בלי להתקין דבר ובלי טווח כתובות ייעודי
 * 6 — כותרת ה-HTTP של רימון. הזולה מכולן, ומאותה תשובה אפשר
 *     לקרוא גם את רמת הסינון של החשבון
 * 7 — מצב תצפית לפיילוט: monitor ו-warn. ראה ההערה למטה
 */
/*
 * מספר התבנית, ולא מספר השורה במסד.
 *
 * הועלה ל-12 כדי לאלץ פרסום מחדש בכל הדיירים, אחרי שהתברר
 * שסוכנים ישנים מחקו שדות שהם אינם מכירים ושמרו את המדיניות
 * בלעדיהם. ETag שלא השתנה פירושו שהמדיניות אינה נמשכת שוב,
 * ולכן השדה שאבד לא היה חוזר לעולם.
 *
 * העלאת המספר משנה את ה-ETag, וכל מחשב מושך גוף שלם.
 */
const BASELINE_VERSION = 14;

export interface BaselineResult {
  created: boolean;
  version: number | null;
}

/**
 * המארחים שנשארים פתוחים גם בחסימה מלאה.
 *
 * שניים, ושניהם הכרחיים: ה-API כדי שהמחשב יוכל לדווח ולקבל
 * שחרור, והפורטל כדי שיהיה **מסך** שאפשר לשחרר ממנו.
 *
 * זה תוקן אחרי שהתגלה בשטח: הסוכן התיר רק את מארח ה-API, והפורטל
 * יושב על מארח אחר. מחשב חסום יכול היה לדווח על עצמו, אבל ההורה
 * שישב מולו לא יכול היה להגיע למסך האישור — והדרך היחידה החוצה
 * עברה במחשב אחר.
 */
export function alwaysAllowHosts(portalUrl: string): string[] {
  /*
   * רק הפורטל.
   *
   * מארח ה-API כבר מותר תמיד: הסוכן גוזר אותו מ-BaseUrl שבתצורה
   * שלו, ואינו זקוק שיאמרו לו. מה שהוא אינו יכול לדעת לבד הוא
   * היכן יושב מרכז הניהול — הוא מעולם לא פונה אליו.
   */
  try {
    const host = new URL(portalUrl).host;

    return host === "" ? [] : [host];
  } catch {
    /*
     * כתובת שאינה תקינה מדולגת — אבל בקול.
     *
     * "החוסר יתגלה בבדיקה" היה נכון בתיאוריה. בפועל הוא מתגלה
     * כשמחשב נחסם ואין לו דרך להגיע למסך שמשחרר אותו, וזו התגלות
     * מאוחרת מדי.
     *
     * הקונפיג חוסם עכשיו כתובת בלי סכימה, ולכן הענף הזה כמעט
     * בלתי אפשרי — וזו בדיוק הסיבה שהוא צריך לצעוק אם בכל זאת
     * הגיע לכאן.
     */
    console.error(
      `  ✗ PORTAL_URL אינו כתובת תקינה: ${portalUrl}
` +
      "    מארח הפורטל לא ייכנס למדיניות, ומחשב חסום לא יוכל להגיע אליו.",
    );

    return [];
  }
}

export function baselineBody(
  now: Date,
  hosts: readonly string[] = [],
  providers: readonly unknown[] = [],
): Record<string, unknown> {
  return {
    version: BASELINE_VERSION,

    // הסימון שלפיו מזוהה תבנית ישנה. ראה ensureBaselinePolicy.
    baselineVersion: BASELINE_VERSION,

    issuedUtc: now.toISOString(),

    // חלון תוקף רחב: מחשב שאיבד קשר לשרת ליום שלם עדיין פועל
    // לפי מה שיש לו, במקום להתייחס למדיניות כפגה ולהחמיר מעצמו.
    ttlMinutes: 240,
    graceMinutes: 1440,

    providers: [...providers],

    enforcement: {
      /*
       * תואם לרצפה שב-PolicyFloorSpec. כל ערך נמוך יותר כאן גורם
       * לסוכן לדחות את החבילה כולה, כולל כללי זיהוי הספקים שאין
       * להם שום קשר להחמרה.
       */
      mode: "monitor",

      /*
       * מה שנשאר פתוח גם כשהכול חסום.
       *
       * בלי הפורטל כאן, חסימה הופכת למלכודת: המחשב מדווח שהוא
       * חסום, וההורה שיושב מולו אינו יכול להגיע למסך שמסיר את
       * החסימה.
       */
      alwaysAllow: {
        hosts: [...hosts],
        ports: [443],
        allowDns: true,
        allowDhcp: true,
        allowLoopback: true,
      },

      minScoreForGreen: 85,
      minScoreForYellow: 60,
      onRedAction: "warn",

      /*
       * תוקף מוגבל למחשב שנותק.
       *
       * אחרי שההסרה הכפויה נסגרה, קוד הסרה נחתם ב-KMS ואין דרך
       * אחרת. מפתח שיאבד, או שירות שייסגר, היו נועלים את כל הצי
       * לצמיתות — גם את המוקד. זו הדרך היחידה שאינה תלויה בשמירת
       * סוד, והיא פותרת גם מחשב שנמכר או משפחה שעזבה.
       *
       * שישים יום, ובנדיבות מכוונת. חלון קצר היה הופך כל חופשה
       * למחשב לא אכוף; ארוך הופך שתיקה לבולטת, וההורה ממילא מקבל
       * התראה על מחשב ששותק הרבה קודם.
       *
       * הערך מגיע מכאן ולא מברירת המחדל שבסוכן, כדי שיהיה אפשר
       * לשנות אותו בלי גרסה חדשה.
       */
      maxOfflineDays: 60,

      egress: buildEgressRule(),
    },
  };
}

/**
 * מוודא שקיימת תבנית גלובלית מעודכנת.
 *
 * נקראת בעליית השרת. כשל אינו מפיל אותה — שרת שעולה בלי תבנית
 * עדיף על שרת שאינו עולה, והמחשבים יקבלו אותה בעלייה הבאה.
 */
export async function ensureBaselinePolicy(
  pool: pg.Pool,
  signer: Signer,
  portalUrl: string,
  now: Date = new Date(),
): Promise<BaselineResult> {
  /*
   * מה שנבדק הוא **תוכן** התבנית, לא מספר הגרסה שלה.
   *
   * מספר הגרסה של המדיניות הגלובלית מטפס בכל עריכת ספק בממשק,
   * ולכן הוא עוקף במהרה את מספר התבנית — ומאותו רגע שום שינוי
   * בקוד לא היה מגיע למחשבים. הסימון נשמר בתוך הגוף עצמו, ולכן
   * הוא נע איתו.
   */
  const existing = await withPlatform(
    pool,
    { userId: "system", reason: "בדיקת מדיניות בסיס" },
    async (tx) => {
      const r = await tx.query<{ version: number; baseline: number | null }>(
        `SELECT version, (body ->> 'baselineVersion')::int AS baseline
           FROM policies WHERE tenant_id IS NULL
          ORDER BY version DESC LIMIT 1`,
      );

      return r.rows[0] ?? null;
    },
  );

  /*
   * הספקים נזרעים תמיד, גם כשהתבנית עדכנית: ספק חדש שנוסף לקוד
   * צריך להגיע לטבלה בלי לדרוס עריכות שנעשו בממשק.
   */
  const seeded = await seedProviders(pool);

  /*
   * ופרסום מחדש כשהזריעה נגעה במשהו — גם אם מספר הגרסה כבר גבוה.
   *
   * בלי התנאי הזה נוצר מלכוד שקט: כל עריכת ספק בממשק מעלה את
   * הגרסה, וברגע שהיא עברה את מספר התבנית, שום שינוי עתידי בזריעה
   * לא היה מגיע למדיניות. הטבלה הייתה מתעדכנת, המחשבים לא — וזה
   * בדיוק סוג הכשל שכבר עלה לנו פעמיים.
   */
  const upToDate = existing !== null && existing.baseline === BASELINE_VERSION;

  /*
   * ההרכבה רצה בכל עלייה, לפני היציאה המוקדמת.
   *
   * היא ישבה אחרי הפרסום בלבד, ולכן מחשב שהתפצל לפני
   * שהתיקון נכנס היה נשאר מפוצל לנצח: הבסיס כבר עדכני,
   * הזריעה מחזירה אפס, הפונקציה יוצאת מוקדם, וההרכבה לא
   * רצה אף פעם. בדיוק המצב שנוצר בפריסה הקודמת.
   *
   * היא אידמפוטנטית — מפרסמת רק כשהתוכן באמת שונה — ולכן
   * הרצה בכל עלייה אינה עולה דבר כשאין מה לעשות.
   */
  await recomposeAll(pool, signer);

  // תבנית עדכנית וזריעה שלא נגעה בדבר — אין מה לפרסם.
  if (upToDate && seeded === 0) {
    return { created: false, version: existing.version };
  }

  const version = await republishBaseline(pool, signer, portalUrl, now);

  /*
   * ושוב אחרי הפרסום, כי הבסיס השתנה זה עתה.
   *
   * הקריאה למעלה ראתה את הבסיס הישן. בלי השנייה, שינוי
   * שנכנס עכשיו היה מגיע למחשבים המשוייכים רק בעלייה הבאה.
   */
  await recomposeAll(pool, signer);

  return { created: true, version };

}

/** הספקים המופעלים, בצורה שנכנסת לחבילה. */
async function policyProviders(pool: pg.Pool): Promise<unknown[]> {
  return toPolicyProviders(await listProviders(pool));
}

/**
 * מפרסם תבנית חדשה אחרי שינוי בספקים.
 *
 * גרסה חדשה בכל קריאה, ולא עדכון של הקיימת: חבילת מדיניות נחתמת
 * פעם אחת על בתים מסוימים, והמחשב מזהה שינוי לפי ETag וגרסה.
 * דריסה של אותה גרסה הייתה משאירה מחשבים על תוכן ישן בלי שידעו.
 *
 * מחזירה את הגרסה שפורסמה.
 */
export async function republishBaseline(
  pool: pg.Pool,
  signer: Signer,
  portalUrl: string,
  now: Date = new Date(),
): Promise<number> {
  const next = await withPlatform(
    pool,
    { userId: "system", reason: "פרסום תבנית אחרי שינוי ספקים" },
    async (tx) => {
      const r = await tx.query<{ version: number }>(
        "SELECT COALESCE(max(version), 0) AS version FROM policies WHERE tenant_id IS NULL",
      );

      return Number(r.rows[0]?.version ?? 0) + 1;
    },
  );

  const published = await publishPolicy(pool, signer, {
    tenantId: null,
    version: next,
    body: baselineBody(now, alwaysAllowHosts(portalUrl), await policyProviders(pool)),
  });

  return published.version;
}

/**
 * מרכיב מחדש את שתי השכבות הנגזרות, בסדר הנכון.
 *
 * הדיירים לפני המחשבים: מדיניות מחשב נבנית מעל מדיניות הדייר,
 * ולכן הרכבה בסדר ההפוך הייתה בונה מחשבים מעל דייר שעדיין ישן.
 *
 * שתיהן אידמפוטנטיות ומפרסמות רק כשהתוכן באמת שונה, ולכן אפשר
 * לקרוא להן בכל עלייה ואחרי כל פרסום בלי מחיר.
 */
async function recomposeAll(pool: pg.Pool, signer: Signer): Promise<void> {
  const tenants = await rebuildTenantPolicies(pool, signer);

  if (tenants > 0) console.log(`  הורכבו מחדש ${tenants} מדיניות דייר מעל הבסיס.`);

  const devices = await rebuildAssignedPolicies(pool, signer);

  if (devices > 0) console.log(`  הורכבו מחדש ${devices} מדיניות מחשב.`);
}
